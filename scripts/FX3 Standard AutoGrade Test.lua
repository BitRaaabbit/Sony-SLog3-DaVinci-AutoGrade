local function collisionSafeOutputBase(resolveObject, fileName)
    local base = stem(fileName) .. "_Rec709_Standard_Test"
    local candidate = base
    if outputNameExists(resolveObject, candidate .. ".mp4") then
        local suffix = os.date("%Y%m%d_%H%M%S")
        candidate = base .. "_" .. suffix
        local number = 2
        while outputNameExists(resolveObject, candidate .. ".mp4") do
            candidate = base .. "_" .. suffix .. "_" .. tostring(number)
            number = number + 1
        end
    end
    return candidate
end

local function addRenderJobForClip(resolveObject, project, timeline, fileName)
    local timelineSet = project:SetCurrentTimeline(timeline)
    local currentTimeline = project:GetCurrentTimeline()
    if not timelineSet and (not currentTimeline or currentTimeline:GetName() ~= timeline:GetName()) then
        fail("Could not select timeline " .. timeline:GetName())
    end
    local renderModeSet = project:SetCurrentRenderMode(0)
    local actualRenderMode = project:GetCurrentRenderMode()
    if tonumber(actualRenderMode) ~= 0 then fail("Could not select and verify Individual Clips render mode.") end
    if not renderModeSet then
        append(state.warnings, "Resolve reported no render-mode change, but Individual Clips mode read back as 0.")
    end

    local formatName, codecName, codecDescription, actualFormat = chooseMp4H264(project)
    local outputBase = collisionSafeOutputBase(resolveObject, fileName)
    local outputPath = OUTPUT_DIR .. "/" .. outputBase .. ".mp4"
    -- Resolve 20.3.2 Free can apply valid encoder settings while returning false
    -- for a multi-key SetRenderSettings call. Submit the officially documented
    -- keys one at a time so an encoder-specific rejection cannot discard the
    -- collision-safe target path, clip name, geometry, or frame rate.
    local documentedSettings = {
        {"SelectAllFrames", true},
        {"TargetDir", OUTPUT_DIR},
        {"CustomName", outputBase},
        {"ExportVideo", true},
        {"ExportAudio", true},
        {"FormatWidth", 3840},
        {"FormatHeight", 2160},
        {"FrameRate", 59.94},
        {"VideoQuality", 100000},
        {"AudioCodec", "aac"},
        {"AudioSampleRate", 48000},
        {"ColorSpaceTag", "Same as Project"},
        {"GammaTag", "Same as Project"},
        {"ReplaceExistingFilesInPlace", false}
    }
    local rejectedSettingNames = {}
    for _, entry in ipairs(documentedSettings) do
        local setting = {}
        setting[entry[1]] = entry[2]
        if not project:SetRenderSettings(setting) then
            append(rejectedSettingNames, entry[1])
        end
    end
    if #rejectedSettingNames > 0 then
        append(state.warnings,
            "Resolve returned false for these individually submitted documented render settings for "
            .. fileName .. ": " .. table.concat(rejectedSettingNames, ", ")
            .. ". The job was added only after setting the collision-safe TargetDir/CustomName and the locked 59.94 timeline; actual job fields are recorded below.")
    end

    local jobId = project:AddRenderJob()
    if not jobId or tostring(jobId) == "" then fail("Could not add render job for " .. fileName) end
    append(state.render_jobs, tostring(jobId) .. " | " .. timeline:GetName() .. " | " .. outputPath)
    append(state.outputs, outputPath)

    state.render_settings["render_mode"] = tostring(project:GetCurrentRenderMode()) .. " (0 = Individual Clips)"
    state.render_settings["format"] = actualFormat.format or formatName
    state.render_settings["video_codec"] = actualFormat.codec or codecName
    state.render_settings["video_codec_description"] = codecDescription or "H.264"
    state.render_settings["resolution"] = "3840x2160"
    state.render_settings["frame_rate"] = "59.94"
    state.render_settings["video_quality_requested_kbps"] = "100000"
    state.render_settings["audio_codec_requested"] = "aac"
    state.render_settings["audio_sample_rate_requested"] = "48000"
    state.render_settings["audio_bitrate"] = "Not exposed by the documented 20.3.2 SetRenderSettings keys; encoder preset/default"
    state.render_settings["replace_existing_files"] = "false"
end

local function describeRenderJobs(project)
    local jobs = project:GetRenderJobList() or {}
    for _, job in ipairs(jobs) do
        local fields = {}
        for key, value in pairs(job) do
            if scalar(value) then append(fields, tostring(key) .. "=" .. tostring(value)) end
        end
        table.sort(fields)
        if #fields > 0 then append(state.render_jobs, "API job snapshot: " .. table.concat(fields, "; ")) end
    end
end

local function phaseOne(resolveObject, project)
    state.phase = "PHASE_1_CONFIGURING_AND_IMPORTING_ONE_CLIP"
    configureProject(project)

    local firstName = TEST_FILES[1]
    local firstPath = INPUT_DIR .. "/" .. firstName
    local firstClip = importOne(project, firstPath)
    append(state.imported_files, firstName)
    setInputColorSpace(project, firstClip, firstName)

    local properties = firstClip:GetClipProperty() or {}
    local codec = properties["Video Codec"] or properties["Codec"] or "not reported"
    local resolution = properties["Resolution"] or "not reported"
    local fps = properties["FPS"] or properties["Frame Rate"] or "not reported"
    append(state.warnings, "Compatibility clip API properties: codec=" .. tostring(codec) .. ", resolution=" .. tostring(resolution) .. ", fps=" .. tostring(fps) .. ". Visual viewer confirmation is still required.")

    local timeline = project:GetMediaPool():CreateTimelineFromClips(COMPAT_TIMELINE, {firstClip})
    if not timeline then fail("Could not create the one-clip compatibility timeline.") end
    setTimelineGeometry(timeline)
    project:SetCurrentTimeline(timeline)
    resolveObject:GetProjectManager():SaveProject()

    state.compatibility = "AWAITING VISUAL CHECK: inspect thumbnail and Edit viewer for image, Media Offline, or audio-only behavior. Do not run phase two unless valid."
    state.phase = "AWAITING_HEVC_VISUAL_CONFIRMATION"
    writeReport()
    resolveObject:OpenPage("edit")
    local startTimecode = timeline:GetStartTimecode()
    if startTimecode and tostring(startTimecode) ~= "" then timeline:SetCurrentTimecode(startTimecode) end
    print("FX3_AUTOGRADE_PHASE_1_READY")
end

local function phaseTwo(resolveObject, project)
    state.phase = "PHASE_2_PREPARING_THREE_RENDER_JOBS"
    state.compatibility = "CONFIRMED by the controlled Edit viewer check before phase two: image visible, not Media Offline, and not audio-only."

    configureProject(project)
    local clips = {}
    for _, fileName in ipairs(TEST_FILES) do
        local fullPath = INPUT_DIR .. "/" .. fileName
        local clip = importOne(project, fullPath)
        clips[fileName] = clip
        append(state.imported_files, fileName)
        setInputColorSpace(project, clip, fileName)
    end

    for _, fileName in ipairs(TEST_FILES) do
        local timelineName = "Render_" .. stem(fileName)
        local timeline = findTimeline(project, timelineName)
        if timeline then
            if #(project:GetRenderJobList() or {}) ~= 0 then
                fail("A render timeline and render jobs already exist; refusing to duplicate or overwrite them: " .. timelineName)
            end
            verifyOneClipTimeline(timeline, fileName)
            append(state.warnings, "Safely reusing the verified one-clip render timeline left by the prior pre-queue stop: " .. timelineName)
        else
            timeline = project:GetMediaPool():CreateTimelineFromClips(timelineName, {clips[fileName]})
            if not timeline then fail("Could not create render timeline " .. timelineName) end
        end
        setTimelineGeometry(timeline)
        addRenderJobForClip(resolveObject, project, timeline, fileName)
    end

    append(state.warnings, "The official 20.3.2 API does not document an AAC bitrate key. AAC 48 kHz was requested; 320 kb/s cannot be guaranteed through the documented API and must be checked in the Deliver UI/job output.")
    describeRenderJobs(project)
    resolveObject:GetProjectManager():SaveProject()
    state.phase = "THREE_RENDER_JOBS_QUEUED_AWAITING_RENDER_START"
    writeReport()
    resolveObject:OpenPage("deliver")
    print("FX3_AUTOGRADE_PHASE_2_READY")
end

local function startOnlyVerifiedTestJobs(resolveObject, project, jobs)
    if #jobs ~= #TEST_FILES then
        fail("The isolated test project has " .. tostring(#jobs) .. " queued jobs, not exactly three. Refusing to start rendering.")
    end

    local expectedByTimeline = {}
    for _, fileName in ipairs(TEST_FILES) do
        expectedByTimeline["Render_" .. stem(fileName)] = stem(fileName) .. "_Rec709_Standard_Test"
    end

    local jobIds = {}
    for _, job in ipairs(jobs) do
        local timelineName = tostring(job.TimelineName or "")
        local expectedOutputPrefix = expectedByTimeline[timelineName]
        local outputFileName = tostring(job.OutputFilename or "")
        local targetDir = string.lower(tostring(job.TargetDir or "")):gsub("\\", "/")
        local formatOk = normalizeText(job.VideoFormat) == "mp4"
        local codecOk = contains(job.VideoCodec, "h.264") or contains(job.VideoCodec, "h264")
        local outputNameOk = expectedOutputPrefix
            and string.sub(outputFileName, 1, #expectedOutputPrefix) == expectedOutputPrefix
            and string.lower(string.sub(outputFileName, -4)) == ".mp4"
        local targetOk = string.sub(targetDir, -16) == "ship_output/test"
        local geometryOk = tonumber(job.FormatWidth) == 3840 and tonumber(job.FormatHeight) == 2160
        local frameRateOk = valueEqualsNumber(job.FrameRate, 59.94)
        local audioOk = job.IsExportAudio == true and normalizeText(job.AudioCodec) == "aac"
            and tonumber(job.AudioSampleRate) == 48000
        local modeOk = contains(job.RenderMode, "individual")
        local jobId = job.JobId or job.RenderJobId
        if not (expectedOutputPrefix and outputNameOk and targetOk and formatOk and codecOk
            and geometryOk and frameRateOk and audioOk and modeOk and jobId) then
            fail("Queued render job verification failed for timeline '" .. timelineName
                .. "'. Refusing to start any render.")
        end
        append(jobIds, tostring(jobId))
        expectedByTimeline[timelineName] = nil
    end
    for timelineName, _ in pairs(expectedByTimeline) do
        fail("The expected test job is missing for timeline " .. timelineName .. ". Refusing to start rendering.")
    end

    if project:IsRenderingInProgress() then
        fail("Resolve is already rendering. Refusing to start another render operation.")
    end
    local started = project:StartRendering(jobIds, true)
    if not started then fail("Resolve refused to start the three verified test render jobs.") end
    resolveObject:OpenPage("deliver")
    print("FX3_AUTOGRADE_THREE_TEST_RENDERS_STARTED")
end

local function main()
    local resolveObject = getResolveObject()
    if not resolveObject then fail("No internal Resolve object is available. Run this script from Workspace > Scripts inside Resolve.") end
    local projectManager = resolveObject:GetProjectManager()
    if not projectManager then fail("Resolve did not return a ProjectManager object.") end

    local project = projectManager:GetCurrentProject()
    if project and project:GetName() ~= PROJECT_NAME then
        fail("A different project is open ('" .. tostring(project:GetName()) .. "'). Return to Project Manager; do not modify that project.")
    end

    if not project then
        if projectExists(projectManager, PROJECT_NAME) then
            fail("A project named " .. PROJECT_NAME .. " already exists. Refusing to load, replace, or overwrite it automatically.")
        end
        project = projectManager:CreateProject(PROJECT_NAME, PROJECT_ROOT .. "/temp")
        if not project then fail("Could not create the unique test project " .. PROJECT_NAME) end
    end

    local existingCompatibilityTimeline = findTimeline(project, COMPAT_TIMELINE)
    if existingCompatibilityTimeline and not valueEqualsNumber(existingCompatibilityTimeline:GetSetting("timelinePlaybackFrameRate"), 59.94) then
        local fileBackedCount = 0
        local unexpectedFileBackedClip = false
        for _, item in ipairs(rootClips(project)) do
            local path = clipFilePath(item)
            if path ~= "" then
                fileBackedCount = fileBackedCount + 1
                if string.lower(basename(path)) ~= string.lower(TEST_FILES[1]) then unexpectedFileBackedClip = true end
            end
        end
        local safeRecoveryState = project:GetTimelineCount() == 1 and fileBackedCount == 1 and not unexpectedFileBackedClip
        if not safeRecoveryState then
            fail("The compatibility timeline is not 59.94 and the project is not in the exact one-clip recovery state. Refusing automatic recovery.")
        end

        append(state.warnings, "The original root-folder test project was preserved because its compatibility timeline was locked at 24 fps. A clean same-named project is being created in Resolve project folder '" .. RECOVERY_PROJECT_FOLDER .. "'; no project is overwritten or deleted.")
        if not projectManager:SaveProject() then fail("Could not save the preserved 24 fps test project before recovery.") end
        if not projectManager:CloseProject(project) then fail("Could not close the preserved 24 fps test project before recovery.") end
        if not projectManager:GotoRootFolder() then fail("Could not navigate to the Resolve project root folder for recovery.") end
        for _, folderName in ipairs(projectManager:GetFolderListInCurrentFolder() or {}) do
            if folderName == RECOVERY_PROJECT_FOLDER then
                fail("The unique recovery project folder already exists; refusing to reuse or overwrite it: " .. RECOVERY_PROJECT_FOLDER)
            end
        end
        if not projectManager:CreateFolder(RECOVERY_PROJECT_FOLDER) then fail("Could not create the unique recovery project folder.") end
        if not projectManager:OpenFolder(RECOVERY_PROJECT_FOLDER) then fail("Could not open the unique recovery project folder.") end
        if projectExists(projectManager, PROJECT_NAME) then fail("A same-named project already exists in the recovery folder; refusing to overwrite it.") end
        project = projectManager:CreateProject(PROJECT_NAME, PROJECT_ROOT .. "/temp")
        if not project then fail("Could not create the clean 59.94 test project in the recovery folder.") end
    end

    local compatibilityTimeline = findTimeline(project, COMPAT_TIMELINE)
    if not compatibilityTimeline then
        local existingClips = rootClips(project)
        local isSafePhaseOneResume = project:GetTimelineCount() == 0
            and #existingClips == 1
            and string.lower(basename(clipFilePath(existingClips[1]))) == string.lower(TEST_FILES[1])
        if project:GetTimelineCount() ~= 0 or (#existingClips ~= 0 and not isSafePhaseOneResume) then
            fail("The target project is not empty and lacks the script's compatibility timeline. Refusing to modify it.")
        end
        if isSafePhaseOneResume then
            append(state.warnings, "Resuming phase one from the one expected compatibility clip after a prior verified stop; no other clips or timelines were present.")
        end
        phaseOne(resolveObject, project)
        return
    end

    local existingRenderJobs = project:GetRenderJobList() or {}
    if #existingRenderJobs > 0 then
        startOnlyVerifiedTestJobs(resolveObject, project, existingRenderJobs)
        return
    end

    phaseTwo(resolveObject, project)
end

local ok, message = pcall(main)
if not ok then
    if #state.failures == 0 then append(state.failures, tostring(message)) end
    state.phase = "FAILED"
    writeReport()
    print("FX3_AUTOGRADE_FAILED: " .. tostring(message))
end
