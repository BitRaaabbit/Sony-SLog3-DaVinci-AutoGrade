local function fail(message)
    append(state.failures, message)
    state.phase = "FAILED"
    writeReport()
    error(message, 0)
end

local function getResolveObject()
    local resolveObject = nil
    if app and app.GetResolve then
        local ok, result = pcall(function() return app:GetResolve() end)
        if ok then resolveObject = result end
    end
    if not resolveObject and type(Resolve) == "function" then
        local ok, result = pcall(function() return Resolve() end)
        if ok then resolveObject = result end
    end
    return resolveObject
end

local function valueEqualsNumber(value, expected)
    local number = tonumber(value)
    return number ~= nil and math.abs(number - expected) < 0.001
end

local function recordSetting(project, key)
    local value = project:GetSetting(key)
    if value ~= nil and tostring(value) ~= "" then
        state.project_settings[key] = value
    end
    return value
end

local function tryProjectSetting(project, key, candidates, validator)
    for _, candidate in ipairs(candidates) do
        local ok = project:SetSetting(key, candidate)
        local actual = project:GetSetting(key)
        if validator(actual) then
            state.project_settings[key] = actual
            return true, actual
        end
    end
    local actual = project:GetSetting(key)
    if actual ~= nil and tostring(actual) ~= "" then
        state.project_settings[key] = actual
    end
    return false, actual
end

local function requireProjectSetting(project, key, candidates, validator, description)
    local ok, actual = tryProjectSetting(project, key, candidates, validator)
    if not ok then
        fail("Could not set and read back " .. description .. " using project setting key '" .. key .. "'. Actual value: " .. tostring(actual))
    end
    return actual
end

local function configureProject(project)
    requireProjectSetting(project, "timelinePlaybackFrameRate", {"59.94", "59.940"}, function(v) return valueEqualsNumber(v, 59.94) end, "playback frame rate 59.94")
    requireProjectSetting(project, "timelineFrameRate", {"59.94", "59.940"}, function(v) return valueEqualsNumber(v, 59.94) end, "timeline frame rate 59.94")
    requireProjectSetting(project, "timelineResolutionWidth", {"3840"}, function(v) return tonumber(v) == 3840 end, "timeline width 3840")
    requireProjectSetting(project, "timelineResolutionHeight", {"2160"}, function(v) return tonumber(v) == 2160 end, "timeline height 2160")

    requireProjectSetting(
        project,
        "colorScienceMode",
        {"davinciYRGBColorManagedv2", "davinciYRGBColorManaged"},
        function(v) return contains(v, "color") and contains(v, "managed") end,
        "DaVinci YRGB Color Managed"
    )

    local customOk = tryProjectSetting(project, "rcmPresetMode", {"Custom"}, function(v) return contains(v, "custom") end)
    local autoOk, autoActual = tryProjectSetting(project, "isAutoColorManage", {"0", "false"}, function(v)
        return tostring(v) == "0" or normalizeText(v) == "false"
    end)
    if not customOk and not autoOk then
        fail("Could not verify that automatic color management is disabled. isAutoColorManage=" .. tostring(autoActual))
    end
    if not autoOk then
        append(state.warnings, "The isAutoColorManage key was unavailable, but rcmPresetMode read back as Custom.")
    end

    tryProjectSetting(project, "separateColorSpaceAndGamma", {"1"}, function(v)
        return tostring(v) == "1" or normalizeText(v) == "true"
    end)

    requireProjectSetting(project, "colorSpaceInput", {"Sony S-Gamut3.Cine", "S-Gamut3.Cine"}, function(v)
        return contains(v, "s-gamut3.cine")
    end, "project input gamut Sony S-Gamut3.Cine")
    requireProjectSetting(project, "colorSpaceInputGamma", {"S-Log3"}, function(v)
        return contains(v, "s-log3")
    end, "project input gamma Sony S-Log3")

    local timelineSpaceOk = tryProjectSetting(project, "colorSpaceTimeline", {"DaVinci WG", "DaVinci Wide Gamut"}, function(v)
        return contains(v, "davinci") and (contains(v, "widegamut") or contains(v, "wg"))
    end)
    local timelineGammaOk = tryProjectSetting(project, "colorSpaceTimelineGamma", {"DaVinci Intermediate"}, function(v)
        return contains(v, "davinci") and contains(v, "intermediate")
    end)
    if not timelineSpaceOk and timelineGammaOk then
        timelineSpaceOk = tryProjectSetting(project, "colorSpaceTimeline", {"DaVinci WG", "DaVinci Wide Gamut"}, function(v)
            return contains(v, "davinci") and (contains(v, "widegamut") or contains(v, "wg"))
        end)
    end
    if not (timelineSpaceOk and timelineGammaOk) then
        local combinedOk = tryProjectSetting(project, "colorSpaceTimeline", {"DaVinci WG/Intermediate", "DaVinci Wide Gamut / Intermediate"}, function(v)
            return contains(v, "davinci") and contains(v, "intermediate")
        end)
        if not combinedOk then
            fail("Could not verify timeline color space as DaVinci Wide Gamut / Intermediate.")
        end
    end

    local outputSpaceOk = tryProjectSetting(project, "colorSpaceOutput", {"Rec.709"}, function(v)
        return contains(v, "rec.709") or contains(v, "rec709")
    end)
    local outputGammaOk = tryProjectSetting(project, "colorSpaceOutputGamma", {"Gamma 2.4", "Gamma2.4"}, function(v)
        return contains(v, "2.4")
    end)
    if not (outputSpaceOk and outputGammaOk) then
        local combinedOk = tryProjectSetting(project, "colorSpaceOutput", {"Rec.709 Gamma 2.4"}, function(v)
            return (contains(v, "rec.709") or contains(v, "rec709")) and contains(v, "2.4")
        end)
        if not combinedOk then
            fail("Could not verify output color space as Rec.709 Gamma 2.4.")
        end
    end

    local allSettings = project:GetSetting() or {}
    for key, value in pairs(allSettings) do
        local lowerKey = string.lower(tostring(key))
        if string.find(lowerKey, "tone", 1, true) or string.find(lowerKey, "gamut", 1, true) or string.find(lowerKey, "mapping", 1, true) then
            if scalar(value) then state.project_settings[key] = value end
        end
    end
end

