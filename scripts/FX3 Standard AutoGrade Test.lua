local function normalizeText(value)
    return string.lower((tostring(value or ""):gsub("%s+", "")))
end

local function compactIdentifier(value)
    return string.lower((tostring(value or ""):gsub("[^%w]", "")))
end

local function contains(value, token)
    return string.find(normalizeText(value), normalizeText(token), 1, true) ~= nil
end

local function basename(path)
    local normalized = tostring(path):gsub("\\", "/")
    return normalized:match("([^/]+)$") or normalized
end

local function stem(path)
    return (basename(path):gsub("%.[^%.]+$", ""))
end

local function append(list, value)
    list[#list + 1] = value
end

local function scalar(value)
    local kind = type(value)
    return kind == "string" or kind == "number" or kind == "boolean"
end

local function tableKeysSorted(tbl)
    local keys = {}
    for key, _ in pairs(tbl or {}) do
        append(keys, tostring(key))
    end
    table.sort(keys)
    return keys
end

local function markdownEscape(value)
    local text = tostring(value or "")
    text = text:gsub("|", "\\|")
    text = text:gsub("\r", " ")
    text = text:gsub("\n", " ")
    return text
end

