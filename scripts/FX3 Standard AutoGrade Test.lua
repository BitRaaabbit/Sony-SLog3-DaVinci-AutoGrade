local function rootClips(project)
    return project:GetMediaPool():GetRootFolder():GetClipList() or {}
end

local function clipFilePath(clip)
    local value = clip:GetClipProperty("File Path")
    if value and tostring(value) ~= "" then return tostring(value) end
    local properties = clip:GetClipProperty() or {}
    for key, propertyValue in pairs(properties) do
        local lowerKey = string.lower(tostring(key))
        if lowerKey == "file path" or lowerKey == "filepath" then
            return tostring(propertyValue or "")
        end
    end
    return ""
end

local function findClipByFile(project, fileName)
    for _, clip in ipairs(rootClips(project)) do
        local path = clipFilePath(clip)
        if string.lower(basename(path)) == string.lower(fileName) then
            return clip
        end
    end
    return nil
end

local function importOne(project, fullPath)
    local existing = findClipByFile(project, basename(fullPath))
    if existing then return existing end
    local imported = project:GetMediaPool():ImportMedia({fullPath}) or {}
    local clip = imported[1]
    if not clip then fail("Resolve failed to import: " .. fullPath) end
    return clip
end

local function findInputColorSpaceKey(clip)
    local properties = clip:GetClipProperty() or {}
    for key, _ in pairs(properties) do
        local lowerKey = string.lower(tostring(key))
        if lowerKey == "input color space" then return key end
        if string.find(lowerKey, "input", 1, true) and string.find(lowerKey, "color", 1, true) and string.find(lowerKey, "space", 1, true) then
            return key
        end
    end
    return "Input Color Space"
end

local function setInputColorSpace(project, clip, fileName)
    local key = findInputColorSpaceKey(clip)
    for _, label in ipairs(INPUT_COLOR_SPACE_LABELS) do
        local ok = clip:SetClipProperty(key, label)
        local actual = clip:GetClipProperty(key)
        if ok and contains(actual, "s-gamut3.cine") and contains(actual, "s-log3") then
            state.input_color_spaces[fileName] = actual
            return actual
        end
    end
    local actual = clip:GetClipProperty(key)
    local projectInputSpace = project:GetSetting("colorSpaceInput")
    local projectInputGamma = project:GetSetting("colorSpaceInputGamma")
    local inheritsProject = normalizeText(actual) == "project" or tostring(actual) == "项目"
    local projectInputVerified = contains(projectInputSpace, "s-gamut3.cine") and contains(projectInputGamma, "s-log3")
    if inheritsProject and projectInputVerified then
        local effective = "Project (" .. tostring(actual) .. ") -> " .. tostring(projectInputSpace) .. " / " .. tostring(projectInputGamma)
        state.input_color_spaces[fileName] = effective
        append(state.warnings, "Per-clip Input Color Space is inherited from the verified project default for " .. fileName .. ": " .. effective .. ".")
        return effective
    end
    fail("Could not set and read back Input Color Space for " .. fileName .. ". Key='" .. tostring(key) .. "', actual='" .. tostring(actual) .. "'.")
end

local function findTimeline(project, name)
    for index = 1, project:GetTimelineCount() do
        local timeline = project:GetTimelineByIndex(index)
        if timeline and timeline:GetName() == name then return timeline end
    end
    return nil
end

local function verifyOneClipTimeline(timeline, fileName)
    local items = timeline:GetItemListInTrack("video", 1) or {}
    if #items ~= 1 then
        fail("Existing render timeline does not contain exactly one video item: " .. timeline:GetName())
    end
    local mediaPoolItem = items[1]:GetMediaPoolItem()
    local actualPath = mediaPoolItem and clipFilePath(mediaPoolItem) or ""
    if string.lower(basename(actualPath)) ~= string.lower(fileName) then
        fail("Existing render timeline does not match the expected source clip: " .. timeline:GetName())
    end
end

local function setTimelineGeometry(timeline)
    local required = {
        {"timelineResolutionWidth", "3840", 3840},
        {"timelineResolutionHeight", "2160", 2160},
        {"timelineFrameRate", "59.94", 59.94},
        {"timelinePlaybackFrameRate", "59.94", 59.94}
    }
    for _, entry in ipairs(required) do
        local key, value, expected = entry[1], entry[2], entry[3]
        local ok = timeline:SetSetting(key, value)
        local actual = timeline:GetSetting(key)
        if not ok and not valueEqualsNumber(actual, expected) then
            fail("Could not verify timeline setting " .. key .. "=" .. value .. "; actual=" .. tostring(actual))
        end
    end
end

local function chooseMp4H264(project)
    local formats = project:GetRenderFormats() or {}
    local formatName = nil
    for name, extension in pairs(formats) do
        if normalizeText(name) == "mp4" or normalizeText(extension) == "mp4" then
            formatName = name
            break
        end
    end
    if not formatName then fail("MP4 render format is not available in this Resolve installation.") end

    local codecs = project:GetRenderCodecs(formatName) or {}
    local codecName = nil
    local codecDescription = nil
    for description, name in pairs(codecs) do
        if contains(description, "h.264") or contains(description, "h264") or contains(name, "h.264") or contains(name, "h264") then
            codecName = name
            codecDescription = description
            break
        end
    end
    if not codecName then fail("H.264 is not available for the MP4 format in this Resolve installation.") end

    local ok = project:SetCurrentRenderFormatAndCodec(formatName, codecName)
    local actual = project:GetCurrentRenderFormatAndCodec() or {}
    local formatMatches = normalizeText(actual.format) == normalizeText(formatName)
        or compactIdentifier(actual.format) == "mp4"
    local codecMatches = compactIdentifier(actual.codec) == compactIdentifier(codecName)
        or string.find(compactIdentifier(actual.codec), "h264", 1, true) ~= nil
    if not (formatMatches and codecMatches) then
        fail("Could not verify MP4/H.264 render format and codec. Set returned=" .. tostring(ok)
            .. ", requested format='" .. tostring(formatName) .. "', requested codec='" .. tostring(codecName)
            .. "', actual format='" .. tostring(actual.format) .. "', actual codec='" .. tostring(actual.codec) .. "'.")
    end
    if not ok then
        append(state.warnings, "Resolve reported no format change, but the current render format read back correctly as "
            .. tostring(actual.format) .. "/" .. tostring(actual.codec) .. ".")
    end
    return formatName, codecName, codecDescription, actual
end

